img = Image.open(SRC).convert("RGB")
px = img.load()


def objhit(box):
    x0, y0, x1, y1 = box
    roof = wall = grey = dark = 0
    for y in range(y0, y1, 2):
        for x in range(x0, x1, 2):
            r, g, b = px[x, y]
            if r > 110 and r > g + 40 and r > b + 55:
                roof += 1
            if r > 150 and 25 < r - g < 85 and 25 < g - b < 85:
                wall += 1
            mx, mn = max(r, g, b), min(r, g, b)
            if mx - mn < 18 and 100 < mx < 175:
                grey += 1
            if r > b + 12 and max(r, g, b) < 105:
                dark += 1
    return roof, wall, grey, dark


