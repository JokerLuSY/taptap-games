def _team_tint(rows):
    """天马整只走阵营色（GBA 做法）：骑手衣服压深两档，白马、白翅膀换成阵营最亮的两档"""
    tr = {"1": "3", "2": "4", "3": "5", "4": "5", "w": "1", "v": "2"}
    return ["".join(tr.get(c, c) for c in r) for r in rows]


