"""第 2–5 章新角色的地图小人像素数据（原创，GBA 火纹风）。字符含义见 fe_units.py，结构同 fe_art.py。

行尾的透明可以省略（生成时补齐）。新增的固定色：w v 白布 亮 / 暗（教会制服、修女头巾），不随阵营变。
"""


_SLIM = {
    "front": {"n": [".....K5KK5K", ".....KmKKmK"], "a": [".....K5KKmK", ".....KmK.KK"], "b": [".....KmKK5K", ".....KK.KmK"]},
    "side": {"n": [".....K5K5K.", ".....KmKmK."], "a": ["....K5KK4K.", "...KmK..KmK"], "b": ["....K4KK5K.", "...KmK..KmK"]},
}
_SLIM["back"] = _SLIM["front"]


def slim_legs(views, cols=(3, 11)):
    """细腿（缇娅那套）走路帧：只替换各视角第 14–15 行的 cols 列区间，区间外（武器尖、披风）沿用原图"""
    out = {}
    for view, pats in _SLIM.items():
        base = [r.ljust(16, ".") for r in views[view][14:16]]
        d = {"row": 14}
        for k, rows in pats.items():
            d[k] = [b[:cols[0]] + p.ljust(16, ".")[cols[0]:cols[1]] + b[cols[1]:] for b, p in zip(base, rows)]
        out[view] = d
    return out


