# -*- coding: utf-8 -*-
"""对比 raw_crop.png 与当前 ch1_bg.png, 验证各补丁是否生效"""
from PIL import Image
import sys

sys.stdout.reconfigure(encoding="utf-8")
RAW = r"E:\projects\taptap\ember_oath\tools\shots\raw_crop.png"
CUR = r"E:\projects\taptap\ember_oath\art\maps\ch1_bg.png"
raw = Image.open(RAW).convert("RGB").load()
cur = Image.open(CUR).convert("RGB").load()

# (标签, 补丁box, 采样点数量)
patches = [
    ("房A+平台 (56,0,292,196)", (56, 0, 292, 196)),
    ("房B (532,0,704,212)", (532, 0, 704, 212)),
    ("房C (12,132,176,266)", (12, 132, 176, 266)),
    ("井路东 (424,84,516,158)", (424, 84, 516, 158)),
    ("井孤儿 (384,176,464,270)", (384, 176, 464, 270)),
    ("房D麦 (693,104,774,202)", (693, 104, 774, 202)),
    ("房D岩 (766,120,810,202)", (766, 120, 810, 202)),
    ("房D草 (693,202,810,264)", (693, 202, 810, 264)),
    ("中南树 (576,206,672,290)", (576, 206, 672, 290)),
    ("台脚树 (732,230,818,294)", (732, 230, 818, 294)),
    ("西岩丘 (40,426,276,640)", (40, 426, 276, 640)),
    ("东金字塔 (566,420,692,552)", (566, 420, 692, 552)),
    ("东南丘 (688,450,960,640)", (688, 450, 960, 640)),
    ("桥水渍 (384,312,464,372)", (384, 312, 464, 372)),
    ("西林越界 (0,138,80,244)", (0, 138, 80, 244)),
    ("未补丁对照 (300,300,400,340)", (300, 300, 400, 340)),
]

for label, (x0, y0, x1, y1) in patches:
    same = diff = 0
    for y in range(y0 + 14, y1 - 14, 7):
        for x in range(x0 + 14, x1 - 14, 7):
            if raw[x, y] == cur[x, y]:
                same += 1
            else:
                diff += 1
    pct = 100 * diff // max(1, same + diff)
    print("%-32s 改变率=%3d%%  (%s)" % (label, pct, "OK 已生效" if pct > 85 else "!! 疑似未生效"))